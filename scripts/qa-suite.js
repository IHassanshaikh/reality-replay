const puppeteer = require("puppeteer-core");
const fs = require("fs");

const BASE_URL = "http://localhost:3000";
const CHROME_PATH = "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe";

const MOCK_PATH_TITLES = new Set([
  "The Grounded Foundation",
  "The Accelerated Leap",
  "The Sovereign Venture",
  "The Deliberate Trajectory",
  "The Dynamic Horizon",
  "The Uncharted Vector",
  "The Balanced Compromise",
]);

async function runApiQA() {
  console.log("=== 1. API & LLM END-TO-END QA ===");
  const results = { passed: 0, failed: 0, details: [] };

  function assert(cond, msg) {
    if (cond) {
      results.passed++;
      console.log(`  [PASS] ${msg}`);
    } else {
      results.failed++;
      console.error(`  [FAIL] ${msg}`);
      results.details.push(msg);
    }
  }

  // 1a. Test GET /api/replays
  const listRes = await fetch(`${BASE_URL}/api/replays`);
  const listData = await listRes.json();
  assert(listRes.status === 200 && listData.success && Array.isArray(listData.replays), "GET /api/replays returns list");

  // 1b. Test POST /api/replays (Live LLM Scenario Generation)
  console.log("  Calling POST /api/replays (Live Gemini 2.5 Flash)...");
  const createPayload = {
    decision: "Should I relocate from Toronto to Austin for a Senior PM role at a fintech, or stay in Toronto to build a boutique UX consultancy?",
    options: [
      { id: "opt_1", label: "Option A", text: "Relocate to Austin for Senior PM role ($185k + equity)" },
      { id: "opt_2", label: "Option B", text: "Stay in Toronto and launch boutique UX consultancy" },
    ],
    context: {
      currentSituation: "Lead Product Designer in Toronto with 6 years experience and strong local network.",
      resources: "$60,000 CAD savings, 2 warm prospective agency clients.",
      constraints: ["Visa/TN sponsorship needed for Austin", "Partner works remotely"],
      timeHorizon: "3 years",
      relevantExperience: "6 years SaaS design, led 4-person design team.",
    },
    userProfile: {
      occupation: "Lead Product Designer",
      industry: "B2B SaaS & Fintech",
      experienceLevel: "Mid-Senior (6+ years)",
      interests: ["Product Strategy", "Entrepreneurship", "Fintech"],
      riskTolerance: "Moderate-High",
      financialRunway: "9-12 months",
    },
    diagnostics: {
      primaryMotivation: "Accelerate career trajectory and ownership",
      worstCaseFear: "Burning through savings with no recurring clients or hating US corporate politics",
      decisionWindow: "Next 30 days",
      stakeholdersImpacted: "Partner and 2 prospective clients",
    },
    priorities: ["Career development", "Personal freedom", "Financial stability"],
  };

  const createRes = await fetch(`${BASE_URL}/api/replays`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(createPayload),
  });
  const createData = await createRes.json();
  assert(
    (createRes.status === 200 || createRes.status === 201) && createData.success && createData.replay?.id,
    `POST /api/replays created replay (${createData.replay?.id})`
  );

  const replay = createData.replay;
  if (replay) {
    assert(replay.scenarios.length === 2, `Generated 2 scenarios (got ${replay.scenarios.length})`);
    const isRealLLM = replay.scenarios.some((s) => !MOCK_PATH_TITLES.has(s.pathTitle));
    assert(
      isRealLLM,
      `Scenarios generated by REAL Gemini LLM (titles: ${replay.scenarios.map((s) => s.pathTitle).join(" | ")})`
    );
    assert(
      replay.scenarios.every((s) => s.timeline.length >= 3),
      "Every scenario has 3+ timeline milestones (Month 3, Year 1, Year 3)"
    );
    assert(
      replay.scenarios.every((s) => Array.isArray(s.assumptions) && s.assumptions.length > 0),
      "Every scenario has interactive assumptions"
    );

    // 1c. Test PATCH /api/scenarios/[id]/assumptions
    const targetScenario = replay.scenarios[0];
    const updatedAssumptions = targetScenario.assumptions.map((a, i) =>
      i === 0 ? { ...a, status: "unlikely" } : a
    );
    const patchRes = await fetch(`${BASE_URL}/api/scenarios/${targetScenario.id}/assumptions`, {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ replayId: replay.id, assumptions: updatedAssumptions }),
    });
    const patchData = await patchRes.json();
    assert(
      patchRes.ok && patchData.success && patchData.replay.scenarios[0].assumptions[0].status === "unlikely",
      "PATCH /api/scenarios/[id]/assumptions persisted status change"
    );

    // 1d. Test POST /api/scenarios/[id]/branch (Live LLM Branching)
    console.log("  Calling POST /api/scenarios/[id]/branch (Live Gemini 2.5 Flash)...");
    const targetEvent = targetScenario.timeline[1] || targetScenario.timeline[0];
    const branchRes = await fetch(`${BASE_URL}/api/scenarios/${targetScenario.id}/branch`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        replayId: replay.id,
        parentScenarioId: targetScenario.id,
        parentEventId: targetEvent.id,
        newDecision: "What if the fintech gets acquired at Year 1 and offers a Director role in NYC?",
        options: [
          "Accept Director role and move to NYC",
          "Take acquisition payout and bootstrap a micro-SaaS",
        ],
      }),
    });
    const branchData = await branchRes.json();
    assert(
      branchRes.ok && branchData.success && Array.isArray(branchData.childScenarios) && branchData.childScenarios.length === 2,
      `POST /api/scenarios/[id]/branch generated 2 child branches`
    );
    if (branchData.childScenarios?.length > 0) {
      const isBranchRealLLM = branchData.childScenarios.some((c) => !c.pathTitle.startsWith("Pivot: "));
      assert(
        isBranchRealLLM,
        `Branches generated by REAL Gemini LLM (titles: ${branchData.childScenarios.map((c) => c.pathTitle).join(" | ")})`
      );
    }

    // 1e. Test GET /api/replays/[id]/compare (Live LLM Comparison)
    console.log("  Calling GET /api/replays/[id]/compare (Live Gemini 2.5 Flash)...");
    const compareRes = await fetch(`${BASE_URL}/api/replays/${replay.id}/compare`);
    const compareData = await compareRes.json();
    assert(
      compareRes.ok &&
        compareData.success &&
        compareData.comparison?.dimensions?.length > 0 &&
        compareData.comparison?.keyDifferences?.length > 0 &&
        compareData.comparison?.priorityAlignment?.length > 0,
      `GET /api/replays/[id]/compare returned ${compareData.comparison?.dimensions?.length} dimensions & ${compareData.comparison?.priorityAlignment?.length} priority alignments`
    );

    // 1f. Test DELETE /api/replays/[id] (Cleanup)
    const delRes = await fetch(`${BASE_URL}/api/replays/${replay.id}`, { method: "DELETE" });
    const delData = await delRes.json();
    assert(delRes.ok && delData.success, `DELETE /api/replays/${replay.id} cleaned up test replay`);

    const verifyDelRes = await fetch(`${BASE_URL}/api/replays/${replay.id}`);
    assert(verifyDelRes.status === 404, "GET deleted replay returns 404");
  }

  // 1g. Test POST /api/contact (validation + success)
  const badContactRes = await fetch(`${BASE_URL}/api/contact`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ name: "A", email: "bad", message: "hi" }),
  });
  assert(badContactRes.status === 400, "POST /api/contact rejects invalid payload with 400");

  const goodContactRes = await fetch(`${BASE_URL}/api/contact`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      name: "QA Tester",
      email: "qa@example.com",
      category: "Feedback",
      subject: "QA Suite Check",
      message: "Verifying contact endpoint works end-to-end.",
    }),
  });
  const goodContactData = await goodContactRes.json();
  assert(goodContactRes.ok && goodContactData.success, "POST /api/contact accepts valid submission");

  return results;
}

async function runBrowserQA() {
  console.log("\n=== 2. BROWSER PAGES, LINKS, CONSOLE & UI QA ===");
  const results = { passed: 0, failed: 0, details: [] };

  function assert(cond, msg) {
    if (cond) {
      results.passed++;
      console.log(`  [PASS] ${msg}`);
    } else {
      results.failed++;
      console.error(`  [FAIL] ${msg}`);
      results.details.push(msg);
    }
  }

  const browser = await puppeteer.launch({
    executablePath: CHROME_PATH,
    headless: "new",
    defaultViewport: { width: 1440, height: 900 },
    args: ["--no-sandbox", "--disable-setuid-sandbox"],
  });

  const pagesToTest = [
    "/",
    "/dashboard",
    "/replay/new",
    "/replay/replay_showcase_career_choice",
    "/replay/replay_showcase_career_choice/compare",
    "/about",
    "/contact",
    "/privacy",
    "/terms",
  ];

  const discoveredLinks = new Set();

  try {
    const page = await browser.newPage();
    const consoleErrors = [];
    const pageErrors = [];
    const failedResponses = [];

    page.on("console", (msg) => {
      if (msg.type() === "error") {
        consoleErrors.push(`${page.url()}: ${msg.text()}`);
      }
    });
    page.on("pageerror", (err) => {
      pageErrors.push(`${page.url()}: ${err.message}`);
    });
    page.on("response", (res) => {
      if (res.status() >= 500) {
        failedResponses.push(`${res.status()} ${res.url()}`);
      }
    });

    for (const route of pagesToTest) {
      const url = `${BASE_URL}${route}`;
      const res = await page.goto(url, { waitUntil: "networkidle0", timeout: 45000 });
      assert(res.status() === 200, `Page ${route} loaded with HTTP 200`);

      const links = await page.evaluate(() => {
        return Array.from(document.querySelectorAll("a[href]"))
          .map((a) => a.getAttribute("href"))
          .filter((h) => h && h.startsWith("/") && !h.startsWith("//"));
      });
      links.forEach((l) => discoveredLinks.add(l));
    }

    // Check all discovered internal links
    console.log(`  Checking ${discoveredLinks.size} unique internal links...`);
    for (const link of discoveredLinks) {
      const r = await fetch(`${BASE_URL}${link}`);
      assert(r.status === 200, `Internal link ${link} returns 200 (got ${r.status})`);
    }

    // Check 404 route
    const notFoundRes = await fetch(`${BASE_URL}/replay/nonexistent_id_xyz`);
    assert(notFoundRes.status === 404, `Nonexistent replay route returns 404 (got ${notFoundRes.status})`);

    // Check robots.txt and sitemap.xml
    const robotsRes = await fetch(`${BASE_URL}/robots.txt`);
    const sitemapRes = await fetch(`${BASE_URL}/sitemap.xml`);
    assert(robotsRes.status === 200, "GET /robots.txt returns 200");
    assert(sitemapRes.status === 200, "GET /sitemap.xml returns 200");

    // Interactive UI Test 1: Canvas Node -> Drawer -> Assumption Explorer -> Branch Modal
    console.log("  Testing interactive Canvas UI (Node click -> Drawer -> Assumption Explorer -> Branch Modal)...");
    await page.goto(`${BASE_URL}/replay/replay_showcase_career_choice`, { waitUntil: "networkidle0" });
    await page.waitForSelector(".react-flow__node-timelineMilestone", { timeout: 10000 });
    await page.click(".react-flow__node-timelineMilestone");
    await page.waitForSelector("button[aria-label='Close detail drawer']", { timeout: 5000 });
    assert(true, "Clicking timeline milestone opens ScenarioDrawer");

    // Click Assumption Explorer button
    const clickedExplorer = await page.evaluate(() => {
      const btns = Array.from(document.querySelectorAll("button"));
      const btn = btns.find((b) => b.textContent.includes("Assumption Explorer"));
      if (btn) {
        btn.click();
        return true;
      }
      return false;
    });
    assert(clickedExplorer, "Clicked Assumption Explorer button");
    await new Promise((r) => setTimeout(r, 400));
    const hasExplorerHeading = await page.evaluate(() =>
      document.body.innerText.includes("Inspect What Needs to Be True")
    );
    assert(hasExplorerHeading, "AssumptionExplorerModal opened cleanly");

    // Interactive UI Test 2: Contact Form submission
    console.log("  Testing interactive Contact Form UI...");
    await page.goto(`${BASE_URL}/contact`, { waitUntil: "networkidle0" });
    const textInputs = await page.$$("form input[type='text']");
    await textInputs[0].type("QA Browser");
    await page.type("form input[type='email']", "qa-browser@example.com");
    if (textInputs[1]) await textInputs[1].type("Automated QA Test");
    await page.type("form textarea", "Testing contact form submission from Puppeteer browser.");
    await page.click("form button[type='submit']");
    await page.waitForFunction(
      () => document.body.innerText.includes("Message Sent Successfully!"),
      { timeout: 10000 }
    );
    assert(true, "Contact form submitted via UI and displayed success state");

    assert(consoleErrors.length === 0, `Zero browser console errors (found: ${consoleErrors.length})`);
    if (consoleErrors.length > 0) console.error("  Console errors:", consoleErrors);

    assert(pageErrors.length === 0, `Zero uncaught page errors (found: ${pageErrors.length})`);
    if (pageErrors.length > 0) console.error("  Page errors:", pageErrors);

    assert(failedResponses.length === 0, `Zero 500 server responses (found: ${failedResponses.length})`);
    if (failedResponses.length > 0) console.error("  500 responses:", failedResponses);
  } finally {
    await browser.close();
  }

  return results;
}

(async () => {
  const apiRes = await runApiQA();
  const browserRes = await runBrowserQA();
  const totalPassed = apiRes.passed + browserRes.passed;
  const totalFailed = apiRes.failed + browserRes.failed;

  console.log(`\n========================================`);
  console.log(`QA SUMMARY: ${totalPassed} PASSED | ${totalFailed} FAILED`);
  console.log(`========================================`);
  if (totalFailed > 0) {
    console.error("Failures:", [...apiRes.details, ...browserRes.details]);
    process.exit(1);
  }
})();
